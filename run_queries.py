"""
Run every query in queries.sql against tokyo_electricity.db and save the results.

    python run_queries.py        (builds the database first if it does not exist)

Output: query_results.md - each question, its SQL and its result table.
"""
import re
import sqlite3
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
DB = HERE / "tokyo_electricity.db"


def parse_queries(path: Path = HERE / "queries.sql") -> list[dict]:
    text = path.read_text(encoding="utf-8")
    blocks = re.split(r"(?m)^-- name: ", text)[1:]
    out = []
    for b in blocks:
        name, rest = b.split("\n", 1)
        question = re.search(r"(?m)^-- question: (.+)$", rest).group(1).strip()
        sql = "\n".join(line for line in rest.splitlines() if not line.startswith("-- question:"))
        sql = re.split(r"(?m)^-- -{10,}", sql)[0].strip()        # stop at the next section header
        out.append({"name": name.strip(), "question": question, "sql": sql})
    return out


def connect() -> sqlite3.Connection:
    if not DB.exists():
        import build_database
        build_database.build()
    return sqlite3.connect(DB)


def run_all() -> list[dict]:
    con = connect()
    results = []
    for q in parse_queries():
        df = pd.read_sql_query(q["sql"], con)
        results.append({**q, "result": df})
    con.close()
    return results


def write_markdown(results, path: Path = HERE / "query_results.md"):
    lines = ["# SQL query results", "",
             "Generated by `run_queries.py` from `queries.sql` on the SQLite database `tokyo_electricity.db`.", ""]
    for r in results:
        lines += [f"## {r['name']}", "", f"**Question:** {r['question']}", "", "```sql", r["sql"], "```", "",
                  r["result"].to_markdown(index=False), ""]
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


if __name__ == "__main__":
    res = run_all()
    pd.set_option("display.width", 200)
    for r in res:
        print(f"\n=== {r['name']}: {r['question']}\n{r['result'].to_string(index=False)}")
    print("\nSaved", write_markdown(res).name)
